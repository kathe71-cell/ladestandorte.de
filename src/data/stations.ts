export function getStationConnectors(station: StationData): StationConnector[] {
  if (station.connectors && station.connectors.length > 0) {
    return station.connectors;
  }
  return station.connectorTypes.map(type => {
    if (type === 'CCS') {
      return { type: 'CCS', maxKw: station.kwMax };
    }
    if (type === 'Typ 2') {
      return { type: 'Typ 2', maxKw: station.kwMax <= 22 ? station.kwMax : 22 };
    }
    if (type === 'CHAdeMO') {
      return { type: 'CHAdeMO', maxKw: Math.min(station.kwMax, 50) };
    }
    return { type, maxKw: station.kwMax <= 22 ? station.kwMax : 22 };
  });
}

export function getStationUrl(station: StationData): string {
  return `/ladestation/${station.citySlug}/${station.slug}`;
}

export function isIndexableLocation(station: StationData): boolean {
  if (!station.id || !station.name || !station.city || !station.citySlug || !station.street || !station.plz) {
    return false;
  }
  if (!station.lat || !station.lng || station.lat === 0 || station.lng === 0) {
    return false;
  }
  if (!station.kwMax || station.kwMax < 50 || !station.connectorTypes || station.connectorTypes.length === 0) {
    return false;
  }
  if (!station.operator || !station.operatorSlug) {
    return false;
  }
  return !!station.isPilot;
}

export function isIndexableMcsLocation(station: StationData): boolean {
  if (!station.truckCharging || !station.truckCharging.supported) {
    return false;
  }
  if (!station.id || !station.name || !station.city || !station.citySlug) {
    return false;
  }
  if (!station.lat || !station.lng || station.lat === 0 || station.lng === 0) {
    return false;
  }
  if (!station.truckCharging.status || !station.truckCharging.source) {
    return false;
  }
  return true;
}

export function getMcsStations(stations: StationData[]): StationData[] {
  return stations.filter(s => isIndexableMcsLocation(s));
}


